//! Local NearSentra network launcher (sandbox only, never a real network).
//!
//! Starts a NEAR sandbox, deploys the vault, creates accounts, and writes all
//! connection details to `<repo>/.localnet/localnet.env` (git-ignored). It then
//! stays alive until SIGINT/SIGTERM so the gateway, sentinel and simulation can
//! talk to it. Run with `make sandbox-deploy`.
#![allow(dead_code)]

#[path = "../tests/helpers.rs"]
mod helpers;

use std::fmt::Write as _;
use std::path::PathBuf;

use helpers::*;
use near_api::types::transaction::actions::{AccessKeyPermission, FunctionCallPermission};
use near_api::{Account, NearToken, Signer};

const AGENTS: usize = 5;

/// Add a function-call access key (restricted to `methods` on the vault) to `owner`
/// and return its secret key string.
async fn add_scoped_key(
    env: &TestEnv,
    owner: &Actor,
    methods: &[&str],
) -> testresult::TestResult<String> {
    let secret = near_api::signer::generate_secret_key()?;
    let public_key = secret.public_key();
    Account(owner.id.clone())
        .add_key(
            AccessKeyPermission::FunctionCall(FunctionCallPermission {
                allowance: Some(NearToken::from_near(2)),
                receiver_id: env.vault.to_string(),
                method_names: methods.iter().map(|m| m.to_string()).collect(),
            }),
            public_key,
        )
        .with_signer(owner.signer.clone())
        .send_to(&env.network)
        .await?
        .assert_success();
    Ok(secret.to_string())
}

#[tokio::main]
async fn main() -> testresult::TestResult<()> {
    let env = setup().await?;
    let _ = Signer::from_secret_key; // keep import used in all cfgs

    let mut out = String::new();
    let rpc = env.sandbox.rpc_addr.to_string();
    writeln!(
        out,
        "# Generated by `make sandbox-deploy`. Sandbox-only keys. Never commit."
    )?;
    writeln!(out, "NEAR_NETWORK=sandbox")?;
    writeln!(out, "NEAR_RPC_URL={rpc}")?;
    writeln!(out, "VAULT_ACCOUNT_ID={}", env.vault)?;
    writeln!(out, "ADMIN_ACCOUNT_ID={}", env.admin.id)?;
    writeln!(out, "ADMIN_PRIVATE_KEY={}", env.admin.secret_key)?;
    writeln!(out, "RECIPIENT_ACCOUNT_ID={}", env.recipient.id)?;
    writeln!(out, "ATTACKER_ACCOUNT_ID={}", env.attacker.id)?;
    writeln!(out, "ATTACKER_PRIVATE_KEY={}", env.attacker.secret_key)?;

    // Sentinel: runtime key can ONLY call pause_agent on the vault.
    let sentinel_key = add_scoped_key(&env, &env.sentinel, &["pause_agent"]).await?;
    writeln!(out, "SENTINEL_ACCOUNT_ID={}", env.sentinel.id)?;
    writeln!(out, "SENTINEL_PRIVATE_KEY={sentinel_key}")?;
    // Worst case for scenario 4: the sentinel account's own full-access key leaks.
    writeln!(
        out,
        "SENTINEL_OWNER_PRIVATE_KEY={}",
        env.sentinel.secret_key
    )?;

    // The default agent from setup() plus extra agents (one per simulation scenario).
    let mut agents: Vec<Actor> = vec![env.agent.clone()];
    for i in 2..=AGENTS {
        agents.push(create_actor(&env.sandbox, &format!("agent{i}"), ACCOUNT_BALANCE).await?);
    }
    for (i, agent) in agents.iter().enumerate() {
        // Agent runtime keys can ONLY call request_transfer on the vault.
        let key = add_scoped_key(&env, agent, &["request_transfer"]).await?;
        let n = i + 1;
        writeln!(out, "AGENT_{n}_ACCOUNT_ID={}", agent.id)?;
        writeln!(out, "AGENT_{n}_PRIVATE_KEY={key}")?;
    }

    // Agent-to-agent demo: ResearchAgent is agent number 6 (scoped request_transfer key, so the
    // gateway can sign for it) and AnalysisAgent is a plain account that only receives payment.
    let research = create_actor(&env.sandbox, "research", ACCOUNT_BALANCE).await?;
    let research_key = add_scoped_key(&env, &research, &["request_transfer"]).await?;
    writeln!(out, "AGENT_{}_ACCOUNT_ID={}", AGENTS + 1, research.id)?;
    writeln!(out, "AGENT_{}_PRIVATE_KEY={research_key}", AGENTS + 1)?;
    let analysis = create_actor(&env.sandbox, "analysis", ACCOUNT_BALANCE).await?;
    writeln!(out, "ANALYSIS_ACCOUNT_ID={}", analysis.id)?;

    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.localnet");
    std::fs::create_dir_all(&dir)?;
    let file = dir.join("localnet.env");
    let tmp = dir.join("localnet.env.tmp");
    std::fs::write(&tmp, &out)?;
    std::fs::rename(&tmp, &file)?; // atomic: readers never see a half-written file

    println!("VAULT_ACCOUNT_ID={}", env.vault);
    println!("NEAR_RPC_URL={rpc}");
    println!("LOCALNET_READY {}", file.canonicalize()?.display());

    if std::env::args().any(|a| a == "--once") {
        // Deploy-and-verify mode: report and exit (sandbox is torn down on drop).
        let _ = std::fs::remove_file(&file);
        return Ok(());
    }

    // Keep the sandbox alive until told to stop.
    let mut term = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())?;
    tokio::select! {
        _ = tokio::signal::ctrl_c() => {}
        _ = term.recv() => {}
    }
    let _ = std::fs::remove_file(&file);
    drop(env);
    Ok(())
}
